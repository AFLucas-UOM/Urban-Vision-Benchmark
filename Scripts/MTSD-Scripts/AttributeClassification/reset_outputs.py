#!/usr/bin/env python3
"""Reset generated AttributeClassification outputs - safely.

Targets ONLY generated experiment artefacts:

    outputs/checkpoints/        trained weights (best.pt etc.)
    outputs/metrics/            per-variant metric JSON/CSV/PNGs
    outputs/reports/            comparison.csv / comparison.md
    outputs/logs/               training logs
    outputs/experiment_log.jsonl
    wandb/                      local W&B run directories

Never touched (they are inputs or expensive derived data):

    Datasets/ (raw images + QA annotations)  - completely out of scope
    outputs/crops/                           - only with --include-crops
    outputs/manifests/                       - only with --include-manifests

Modes (mutually exclusive):

    (default)   dry run - list what WOULD be archived/deleted, change nothing
    --archive   move targets into outputs/_archive/<timestamp>/
    --delete    permanently delete targets (asks for confirmation; --yes skips)

Examples:
    python reset_outputs.py                       # dry run
    python reset_outputs.py --archive             # safe reset before a rerun
    python reset_outputs.py --delete              # delete after confirmation
    python reset_outputs.py --archive --include-crops --include-manifests
"""

from __future__ import annotations

import argparse
import shutil
import sys
from datetime import datetime
from pathlib import Path

SUBPROJECT = Path(__file__).resolve().parent
OUTPUTS = SUBPROJECT / "outputs"

DEFAULT_TARGETS = [
    OUTPUTS / "checkpoints",
    OUTPUTS / "metrics",
    OUTPUTS / "reports",
    OUTPUTS / "logs",
    OUTPUTS / "experiment_log.jsonl",
    SUBPROJECT / "wandb",
]
PROTECTED_TARGETS = {
    "crops": OUTPUTS / "crops",
    "manifests": OUTPUTS / "manifests",
}


def _size_of(path: Path) -> int:
    if path.is_file():
        return path.stat().st_size
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file())


def _fmt_size(num_bytes: int) -> str:
    value = float(num_bytes)
    for unit in ("B", "KB", "MB", "GB", "TB"):
        if value < 1024 or unit == "TB":
            return f"{value:,.1f} {unit}"
        value /= 1024
    return f"{value:,.1f} TB"


def collect_targets(include_crops: bool, include_manifests: bool) -> list[Path]:
    targets = list(DEFAULT_TARGETS)
    if include_crops:
        targets.append(PROTECTED_TARGETS["crops"])
    if include_manifests:
        targets.append(PROTECTED_TARGETS["manifests"])
    return [t for t in targets if t.exists()]


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--archive", action="store_true",
                      help="Move targets to outputs/_archive/<timestamp>/ instead of deleting.")
    mode.add_argument("--delete", action="store_true",
                      help="Permanently delete targets (asks for confirmation).")
    parser.add_argument("--include-crops", action="store_true",
                        help="ALSO reset outputs/crops/ (expensive to regenerate).")
    parser.add_argument("--include-manifests", action="store_true",
                        help="ALSO reset outputs/manifests/ (regenerated by run_all.py).")
    parser.add_argument("--yes", action="store_true",
                        help="Skip the --delete confirmation prompt.")
    args = parser.parse_args()

    targets = collect_targets(args.include_crops, args.include_manifests)
    if not targets:
        print("Nothing to reset - no generated outputs found.")
        return

    action = "DELETE" if args.delete else ("ARCHIVE" if args.archive else "DRY RUN")
    print(f"Mode: {action}\n")
    total = 0
    for target in targets:
        size = _size_of(target)
        total += size
        kind = "dir " if target.is_dir() else "file"
        print(f"  {kind}  {target.relative_to(SUBPROJECT)}  ({_fmt_size(size)})")
    print(f"\n  total: {_fmt_size(total)}")
    for name, path in PROTECTED_TARGETS.items():
        flag = f"--include-{name}"
        included = (name == "crops" and args.include_crops) or (
            name == "manifests" and args.include_manifests)
        if path.exists() and not included:
            print(f"  kept : {path.relative_to(SUBPROJECT)}  (protected; use {flag})")

    if not (args.archive or args.delete):
        print("\nDry run only - nothing was changed. "
              "Use --archive (recommended) or --delete.")
        return

    if args.delete and not args.yes:
        answer = input("\nType 'DELETE' to permanently remove the listed outputs: ").strip()
        if answer != "DELETE":
            print("Aborted - nothing was changed.")
            return

    if args.archive:
        archive_root = OUTPUTS / "_archive" / datetime.now().strftime("%Y%m%d-%H%M%S")
        archive_root.mkdir(parents=True, exist_ok=True)
        for target in targets:
            destination = archive_root / target.name
            shutil.move(str(target), str(destination))
            print(f"archived {target.name} -> {destination.relative_to(SUBPROJECT)}")
        print(f"\nDone. Archive: {archive_root}")
    else:
        for target in targets:
            if target.is_dir():
                shutil.rmtree(target)
            else:
                target.unlink()
            print(f"deleted {target.relative_to(SUBPROJECT)}")
        print("\nDone.")


if __name__ == "__main__":
    sys.exit(main())
